from playwright.sync_api import sync_playwright
import traceback,json
with sync_playwright() as p:
 b=p.chromium.launch(headless=True,executable_path='/usr/bin/chromium',args=['--no-sandbox','--disable-dev-shm-usage','--allow-file-access-from-files','--disable-web-security'])
 page=b.new_page(viewport={'width':390,'height':844},device_scale_factor=1)
 errs=[]
 page.on('pageerror',lambda e:errs.append(str(e)))
 page.on('console',lambda m:errs.append('console:'+m.text) if m.type=='error' else None)
 page.goto('file:///mnt/data/bodypath-dev-01161/index.html',wait_until='domcontentloaded',timeout=20000)
 page.wait_for_timeout(1800)
 print('title:',page.title())
 print('loaded:',page.evaluate('typeof getBP61State'))
 print('page errors:',errs[:15])
 print('tree:',page.locator('#skillTree').count())
 # trigger tree via nav button
 page.locator('#homeNavTreeBtn').click()
 page.wait_for_timeout(450)
 print('tree levels',page.locator('.bp61-goal').count(),'tree rank',page.locator('.bp61-rank').count())
 print('active:',page.locator('.bp61-goal.active').count())
 print('tree size',page.locator('.bp61-canvas').bounding_box())
 print('scroll',page.evaluate('({scroll:document.getElementById("treeScroll")?.scrollTop,doc:document.documentElement.scrollHeight})'))
 page.locator('[data-bp61-level="A5"]').click()
 print('modal',page.locator('#bp61Sheet').get_attribute('class'),'button:',page.locator('#bp61SheetStart').inner_text())
 page.screenshot(path='/mnt/data/bodypath-dev-01161/preview-level.png')
 page.locator('#bp61SheetStart').click()
 page.wait_for_timeout(400)
 print('training shown',page.locator('#trainingModal').get_attribute('class'),'selected',page.locator('.workout-variant-btn.selected').count())
 print('challenge banner',page.locator('#bp61TrainingBanner').inner_text())
 print('page errors:',errs[-12:])
 page.locator('#closeTrainingBtn').click()
 page.evaluate('showView("tree")')
 page.wait_for_timeout(250)
 page.locator('#treeScroll').evaluate('(el)=>el.scrollTop=0')
 page.wait_for_timeout(250)
 page.screenshot(path='/mnt/data/bodypath-dev-01161/preview-bronze.png',full_page=False)
 page.evaluate('document.getElementById("treeScroll").scrollTop= document.getElementById("treeScroll").scrollHeight')
 page.wait_for_timeout(200)
 page.screenshot(path='/mnt/data/bodypath-dev-01161/preview-start.png',full_page=False)
 b.close()
